import AppKit
import SwiftUI

/// Historique du presse-papiers : texte, liens et images, en mémoire seulement.
///
/// macOS ne notifie pas les copies : on compare `changeCount` deux fois par seconde.
/// Les contenus marqués confidentiels ou éphémères (convention nspasteboard.org, utilisée
/// par 1Password, Bitwarden, le trousseau…) ne sont jamais gardés.
final class ClipboardMonitor {
    static let limit = 30

    private let model: NotchModel
    private let pasteboard = NSPasteboard.general
    private var lastChange: Int
    private var timer: Timer?
    /// Appelé sur un double ⌘C : deux copies identiques coup sur coup.
    var onDoubleCopy: (() -> Void)?
    private var lastCopy: (date: Date, signature: String)?

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    init(model: NotchModel) {
        self.model = model
        lastChange = pasteboard.changeCount
        // 20 fois par seconde : assez pour distinguer deux ⌘C rapprochés, et la lecture ne coûte presque rien.
        timer = Timer.scheduledTimer(withTimeInterval: 0.05, repeats: true) { [weak self] _ in self?.poll() }
    }

    private func poll() {
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        guard AppSettings.shared.clipboardHistory else { return }

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        var item = ClipItem(date: Date())
        item.app = NSWorkspace.shared.frontmostApplication?.localizedName
        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            item.text = text
        } else if let image = NSImage(pasteboard: pasteboard) {
            item.image = image
        } else {
            return // fichiers et autres formats : l'étagère s'en charge
        }

        detectDoubleCopy(item)

        // Une même copie répétée remonte en tête au lieu de se dupliquer.
        var list = model.clipboard
        if let text = item.text { list.removeAll { $0.text == text } }
        list.insert(item, at: 0)
        model.clipboard = Array(list.prefix(Self.limit))
    }

    /// Double ⌘C : la même chose copiée deux fois, entre 0,08 et 0,6 s d'écart.
    /// Le plancher écarte les apps qui écrivent deux fois dans le presse-papiers pour une seule copie.
    private func detectDoubleCopy(_ item: ClipItem) {
        let signature = item.text ?? item.image.map { "image-\($0.size)" } ?? ""
        let now = Date()
        let previous = lastCopy
        lastCopy = (now, signature)
        guard AppSettings.shared.doubleCopyPopup, let last = previous else { return }
        let gap = now.timeIntervalSince(last.date)
        debugLog("presse-papiers: copie, \(Int(gap * 1000)) ms après la précédente, même contenu \(last.signature == signature)")
        guard last.signature == signature else { return }
        if gap >= 0.05 && gap <= 0.8 {
            lastCopy = nil // un triple ⌘C n'ouvre pas une deuxième fois
            debugLog("presse-papiers: double copie détectée (\(Int(gap * 1000)) ms)")
            DispatchQueue.main.async { self.onDoubleCopy?() }
        }
    }

    /// Remet un élément dans le presse-papiers et le remonte en tête.
    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        if let text = item.text {
            pasteboard.setString(text, forType: .string)
        } else if let image = item.image {
            pasteboard.writeObjects([image])
        }
        lastChange = pasteboard.changeCount
        var list = model.clipboard
        list.removeAll { $0.id == item.id }
        var moved = item
        moved.date = Date()
        list.insert(moved, at: 0)
        withAnimation(.spring(response: 0.35, dampingFraction: 0.85)) { model.clipboard = list }
        Haptics.tap()
    }
}
